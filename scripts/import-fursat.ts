/**
 * Imports FURSAT data from the website repo (single source of truth) into:
 *   supabase/seed.sql                         run once in the Supabase SQL editor (idempotent)
 *   apps/guest/public/data/fursat-menu.json   offline snapshot used by the guest app
 *   docs/import-report.md                     counts + every TODO(client)
 *   apps/guest/public/menu/...                dish photos referenced by dish-photos.json (copied)
 *
 * Usage:  pnpm import:fursat ../fursat-astro
 *    or:  FURSAT_SITE=/workspaces/fursat-astro pnpm import:fursat
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { importMenu, rupeesToPaise, type SourcePhoto, type SourceSection } from "../packages/core/src";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const site = resolve(process.argv[2] ?? process.env.FURSAT_SITE ?? "../fursat-astro");
const data = (f: string) => JSON.parse(readFileSync(join(site, "src/data", f), "utf8"));
if (!existsSync(join(site, "src/data/food.json"))) {
  console.error(`Website repo not found at ${site}. Pass the path: pnpm import:fursat /workspaces/fursat-astro`);
  process.exit(1);
}

const TENANT = "fursat";
const food: SourceSection[] = data("food.json");
const drinks: SourceSection[] = data("drinks.json");
const photos: Record<string, SourcePhoto> = data("dish-photos.json").photos ?? {};
const party = data("party.json") as { groups: { id: string; label: string; blurb: string }[]; packages: { id: string; group: string; name: string; price: number }[] };
const siteJson = data("site.json");

const menu = importMenu(TENANT, food, drinks, photos);

// Demo tables until FURSAT sends the real list (TODO(client)): Cafe C1-C3, Restaurant R1-R5, Bar B1-B4.
const zones = [
  { id: "fursat:cafe", name: "Café", sort: 0 },
  { id: "fursat:restaurant", name: "Restaurant", sort: 1 },
  { id: "fursat:bar", name: "Bar", sort: 2 },
  { id: "fursat:banquet", name: "Banquets", sort: 3 },
];
const tables = [
  ...[1, 2, 3].map((n) => ({ code: `C${n}`, label: `Café ${n}`, zone: "fursat:cafe" })),
  ...[1, 2, 3, 4, 5].map((n) => ({ code: `R${n}`, label: `Table ${n}`, zone: "fursat:restaurant" })),
  ...[1, 2, 3, 4].map((n) => ({ code: `B${n}`, label: `Bar ${n}`, zone: "fursat:bar" })),
];

const settings = {
  gstBps: 500, // TODO(client): confirm 5% restaurant GST with FURSAT's accountant
  intraState: true,
  barOrdersViaQr: false, // TODO(client): may alcohol be ordered by QR? false until FURSAT confirms
  allowAutoOpen: true, // pilot: first scan opens the table; switch off once staff open tables from the board
  hours: siteJson.hours,
  phone: siteJson.phone,
  whatsapp: siteJson.whatsapp,
  mapsUrl: siteJson.address?.googleMaps,
};

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const row = (vals: unknown[]) => `(${vals.map(q).join(", ")})`;

const sql: string[] = [
  "-- Generated by scripts/import-fursat.ts. Do not edit by hand; re-run the importer.",
  `-- Source: ${site} (food ${menu.items.filter((i) => i.id.includes(":food:")).length}, drinks ${menu.items.filter((i) => i.id.includes(":drinks:")).length})`,
  "begin;",
  `insert into public.tenants (slug, name, settings) values ${row([TENANT, siteJson.name, settings])}`,
  "  on conflict (slug) do update set name = excluded.name, settings = excluded.settings;",
  `insert into public.zones (id, tenant, name, sort) values\n${zones.map((z) => row([z.id, TENANT, z.name, z.sort])).join(",\n")}`,
  "  on conflict (id) do update set name = excluded.name, sort = excluded.sort;",
  `insert into public.menu_sections (id, tenant, side, name, sort, is_bar) values\n${menu.sections.map((s) => row([s.id, s.tenant, s.side, s.name, s.sort, s.is_bar])).join(",\n")}`,
  "  on conflict (id) do update set name = excluded.name, sort = excluded.sort, is_bar = excluded.is_bar;",
  `insert into public.menu_items (id, tenant, section_id, source_name, description, price_paise, is_veg, spicy, chef_special, is_bar, photo, photo_unconfirmed, sort) values\n${menu.items
    .map((i) => row([i.id, i.tenant, i.section_id, i.source_name, i.description, i.price_paise, i.is_veg, i.spicy, i.chef_special, i.is_bar, i.photo, i.photo_unconfirmed, i.sort]))
    .join(",\n")}`,
  "  on conflict (id) do update set source_name = excluded.source_name, description = excluded.description, price_paise = excluded.price_paise, is_veg = excluded.is_veg, spicy = excluded.spicy, chef_special = excluded.chef_special, is_bar = excluded.is_bar, photo = excluded.photo, photo_unconfirmed = excluded.photo_unconfirmed, sort = excluded.sort;",
  "-- items removed from the website menu are marked unavailable, never deleted (orders keep their history)",
  `update public.menu_items set available = false where tenant = '${TENANT}' and id not in (${menu.items.map((i) => q(i.id)).join(", ")});`,
  `insert into public.packages (id, tenant, grp, name, price_paise, details, sort) values\n${party.packages
    .map((p, i) => row([`${TENANT}:${p.id}`, TENANT, p.group, p.name, rupeesToPaise(p.price), { ...p, unit: "per guest (TODO(client): confirm)" }, i]))
    .join(",\n")}`,
  "  on conflict (id) do update set grp = excluded.grp, name = excluded.name, price_paise = excluded.price_paise, details = excluded.details, sort = excluded.sort;",
  `insert into public.dining_tables (tenant, code, label, zone_id) values\n${tables.map((t) => row([TENANT, t.code, t.label, t.zone])).join(",\n")}`,
  "  on conflict (tenant, code) do nothing;",
  "commit;",
];
mkdirSync(join(root, "supabase"), { recursive: true });
writeFileSync(join(root, "supabase/seed.sql"), sql.join("\n") + "\n");

// Offline snapshot for the guest app (same shape the app gets from Supabase)
const snapshot = {
  tenant: TENANT,
  generatedAt: new Date().toISOString(),
  sections: menu.sections,
  items: menu.items,
  packages: party.packages.map((p) => ({ id: `${TENANT}:${p.id}`, group: p.group, name: p.name, price_paise: rupeesToPaise(p.price) })),
  packageGroups: party.groups,
  zones,
  site: { phone: siteJson.phone, whatsapp: siteJson.whatsapp, hours: siteJson.hours, maps: siteJson.address?.googleMaps, instagram: siteJson.social?.instagram },
};
mkdirSync(join(root, "apps/guest/public/data"), { recursive: true });
writeFileSync(join(root, "apps/guest/public/data/fursat-menu.json"), JSON.stringify(snapshot));

// Copy referenced dish photos (small size) so the app works offline and in the store build
let copied = 0;
const missing: string[] = [];
for (const it of menu.items) {
  if (!it.photo) continue;
  const from = join(site, "public", it.photo);
  const to = join(root, "apps/guest/public", it.photo);
  if (existsSync(from)) {
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(from, to);
    copied++;
  } else missing.push(it.photo);
}

// Report
const foodCount = menu.items.filter((i) => i.id.includes(":food:")).length;
const drinkCount = menu.items.filter((i) => i.id.includes(":drinks:")).length;
const report = [
  `# FURSAT import report`,
  ``,
  `Source: \`${site}\` · generated ${new Date().toISOString()}`,
  ``,
  `| | Sections | Items | With photo |`,
  `|---|---|---|---|`,
  `| Food | ${menu.sections.filter((s) => s.side === "food").length} | ${foodCount} | ${menu.items.filter((i) => i.id.includes(":food:") && i.photo).length} |`,
  `| Drinks | ${menu.sections.filter((s) => s.side === "drinks").length} | ${drinkCount} (bar/alcohol: ${menu.items.filter((i) => i.is_bar).length}) | ${menu.items.filter((i) => i.id.includes(":drinks:") && i.photo).length} |`,
  ``,
  `Party packages: ${party.packages.length} · demo tables: ${tables.length} (TODO(client): real table list) · photos copied: ${copied}${missing.length ? ` · missing files: ${missing.length}` : ""}`,
  ``,
  `## Per section`,
  ``,
  ...menu.report.map((r) => `- ${r.side} / ${r.section}: ${r.items} items, ${r.withPhoto} with photo`),
  ``,
  `## TODO(client)`,
  ``,
  `- Confirm 5% GST rate and that prices exclude GST.`,
  `- May alcohol be ordered by QR? (barOrdersViaQr = false until confirmed)`,
  `- Real table list (codes, zones, seats).`,
  `- Party prices are read as per guest (as on the website) — confirm.`,
  ...menu.warnings.map((w) => `- ${w}`),
  ...missing.map((m) => `- photo file missing: ${m}`),
  ``,
].join("\n");
writeFileSync(join(root, "docs/import-report.md"), report);
console.log(`Imported food ${foodCount}, drinks ${drinkCount}, packages ${party.packages.length}, photos ${copied}. Wrote supabase/seed.sql, apps/guest/public/data/fursat-menu.json, docs/import-report.md`);
